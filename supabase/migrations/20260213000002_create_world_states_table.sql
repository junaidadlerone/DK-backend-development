-- Create world_states table
CREATE TABLE IF NOT EXISTS world_states (
  id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
  country_id UUID NOT NULL REFERENCES countries(id) ON DELETE CASCADE,
  name TEXT NOT NULL,
  code TEXT,
  created_at TIMESTAMPTZ DEFAULT NOW(),
  UNIQUE(country_id, name)
);

-- Enable RLS
ALTER TABLE world_states ENABLE ROW LEVEL SECURITY;

-- Policies
CREATE POLICY "Public read access to world_states"
  ON world_states FOR SELECT
  TO authenticated, anon
  USING (true);

CREATE POLICY "Service role has full access to world_states"
  ON world_states FOR ALL
  TO service_role
  USING (true)
  WITH CHECK (true);

-- Create indexes
CREATE INDEX idx_world_states_country_id ON world_states(country_id);
CREATE INDEX idx_world_states_code ON world_states(code);

