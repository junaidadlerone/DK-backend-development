// Hoisted and built without template literals: the class contains `${`, which inside a template literal
// reads as the start of an interpolation.
const REGEX_SPECIALS = /[.*+?^${}()|[\]\\]/g;
/** A route pattern → matcher. `:param` is one segment; `:param?` is an optional one. */
function routeMatcher(pattern) {
  const parts = pattern.split("/").filter(Boolean).map((seg) => {
    if (seg.startsWith(":")) return seg.endsWith("?") ? "(?:/[^/]+)?" : "/[^/]+";
    return "/" + seg.replace(REGEX_SPECIALS, "\\$&");
  });
  // Trailing slash tolerated, case-insensitive: React Router matches that way by default.
  return new RegExp("^" + (parts.join("") || "/") + "/?$", "i");
}
const MATCHERS = ROUTES ? ROUTES.map((r) => routeMatcher(r)) : null;
const LINKABLE_MATCHERS = LINKABLE ? LINKABLE.map((r) => routeMatcher(r)) : null;
const matchesAny = (list, path) => !!list?.some((re) => re.test(path));

/** The path part of an in-app href, without query or hash. Null when it is not a bare path. */
export function pathOf(href) {
  const raw = String(href ?? "");
  if (!raw.startsWith("/")) return null;
  return raw.split("?")[0].split("#")[0];
}

const USE_INSTEAD = "For an ACTION, use the purpose-built component rather than a link: address verification → VerifyAddressesButton{campaign_id, campaign_name}; launching → LaunchButton{campaign_id, campaign_name}; attaching a CSV → AddressListUploader{campaign_id}; setting an audience → AudienceBuilder{campaign_id}; adding a photo or logo → ImageUploader{target}; switching organization → OrgSwitchButton. Each opens the real in-app flow where the user reviews and confirms.";

/**
 * Refusal text for any unusable link in the frame, else null.
 *
 * Route checking degrades OPEN when the artifact carries no `routes` (a service deployed before the
 * artifact was re-copied): it must never refuse links it simply cannot verify. The openUrl rule needs
 * no artifact and therefore always applies.
 */
export function checkLinks(components) {
  for (const n of components ?? []) {
    const action = n?.props?.action;

    if (action?.type === "openUrl") {
      return `component "${n.id}" uses action {type:"openUrl"}, which is not allowed: you composed that url, and the app's real addresses are not something you can know. ${USE_INSTEAD} To send the user to a screen, use NavButton{href} or action {type:"navigate", href:"/path"} with one of these in-app paths: ${(LINKABLE ?? []).slice(0, 14).join(", ")} — substituting a real id, from a tool result, for any :param.`;
    }

    const href = action?.type === "navigate" ? action.href : (n?.type === "NavButton" ? n.props?.href : null);
    const path = pathOf(href);
    if (path === null || !MATCHERS) continue; // not a judgeable path, or no oracle available

    if (!matchesAny(MATCHERS, path)) {
      return `component "${n.id}" links to "${path}", which is NOT a screen in this app — that path was composed rather than read from a tool result, so it will not open. ${USE_INSTEAD} The real screens are: ${(LINKABLE ?? []).slice(0, 14).join(", ")}. Substitute a real id for any :param.`;
    }
    if (LINKABLE_MATCHERS && !matchesAny(LINKABLE_MATCHERS, path)) {
      return `component "${n.id}" links to "${path}", which is a real page but NOT one to send the user to — you are not available there, so the conversation would disappear. Keep the user inside the app: ${(LINKABLE ?? []).slice(0, 14).join(", ")}.`;
    }
  }
  return null;
}


// Validate a full frame. Returns { ok:true, frame } or { ok:false, error }.
export function validateUiFrame(input) {
  if (!input || typeof input !== "object") return { ok: false, error: "frame must be an object" };
  const surface_id = input.surface_id;
  if (typeof surface_id !== "string" || !surface_id) return { ok: false, error: "surface_id (string) is required" };
  const root = input.root;
  if (typeof root !== "string" || !root) return { ok: false, error: "root (component id) is required" };
  const mode = input.mode ?? "replace";
  if (mode !== "replace") return { ok: false, error: `mode must be "replace" (patch is reserved)` };
  if (!Array.isArray(input.components) || input.components.length === 0) return { ok: false, error: "components must be a non-empty array" };
  if (input.components.length > MAX_COMPONENTS) return { ok: false, error: `too many components (${input.components.length} > ${MAX_COMPONENTS})` };

  const byId = new Map();
  const normalized = [];
  for (const entry of input.components) {
    const n = normalizeEntry(entry);
    if (!n || n.error) return { ok: false, error: n?.error ?? "invalid component entry" };
    if (byId.has(n.id)) return { ok: false, error: `duplicate component id "${n.id}"` };
    if (!COMPONENT_TYPES.includes(n.type)) return { ok: false, error: `unknown component type "${n.type}" (id "${n.id}")` };
    byId.set(n.id, n);
    normalized.push(n);
  }
  if (!byId.has(root)) return { ok: false, error: `root "${root}" is not among the components` };

  // Fractional opacities are corrected BEFORE prop validation, so the fixed value is what gets
  // validated, streamed, previewed and eventually baked into the saved HTML.
  const opacityFixes = [];
  for (const n of normalized) {
    if (n.type === "TemplateProposal") opacityFixes.push(...normalizeSpecOpacity(n.props));
  }

  // Per-component prop validation against the catalog schema (strip-parity with the frontend:
  // unknown extra properties are removed, not fatal — see validateComponentProps).
  for (const n of normalized) {
    const result = validateComponentProps(n.type, n.props);
    if (!result.ok) {
      return { ok: false, error: `${n.type} "${n.id}": ${result.error}` };
    }
    n.props = result.props;
  }

  // Runs AFTER prop validation so the props are normalized (and any unknown keys stripped) before the
  // action is inspected — otherwise a frame could be refused for a property that was about to be
  // dropped anyway.
  const linkError = checkLinks(normalized);
  if (linkError) return { ok: false, error: linkError };

  // A singleton card's id is derived from what it acts on, not from what the model typed (see
  // SINGLETON_SURFACES). Computed after prop validation so the identifying props are the normalized ones.
  const derivedId = derivedSurfaceId(normalized);
  const effectiveSurfaceId = derivedId ?? surface_id;

  // Referential integrity + depth + cycle check from root.
  const walk = (id, depth, path) => {
    if (depth > MAX_DEPTH) return `nesting exceeds ${MAX_DEPTH} at "${id}"`;
    if (path.has(id)) return `cycle detected at "${id}"`;
    const n = byId.get(id);
    if (!n) return `referenced component "${id}" does not exist`;
    const childKey = CONTAINER_KEYS[n.type];
    if (childKey) {
      const kids = n.props?.[childKey];
      if (Array.isArray(kids)) {
        const nextPath = new Set(path); nextPath.add(id);
        for (const k of kids) {
          const err = walk(k, depth + 1, nextPath);
          if (err) return err;
        }
      }
    }
    return null;
  };
  const err = walk(root, 1, new Set());
  if (err) return { ok: false, error: err };

  return {
    ok: true,
    // Reported back through the tool result so the model sees the correction rather than repeating it
    // next turn (and does not describe a band as 55% when it wrote 0.55).
    ...(opacityFixes.length ? { opacityFixes } : {}),
    ...(derivedId && derivedId !== surface_id ? { derivedSurfaceId: derivedId, requestedSurfaceId: surface_id } : {}),
    frame: {
      type: "ui",
      surface_id: effectiveSurfaceId,
      mode: "replace",
      root,
      // Always emit the canonical/preferred wire form {id, component:{Type:props}}
      // regardless of which form the model produced — the frontend prefers this one.
      components: normalized.map((n) => ({ id: n.id, component: { [n.type]: n.props } })),
      data_model: (input.data_model && typeof input.data_model === "object") ? input.data_model : {},
    },
  };
}

// ── a design proposal is a NEW design, never an edit (2026-08-04) ─────────────
// REPORTED LIVE. The user asked, over several turns, to "add picture on the back side of this template"
// and "add the tag line thank you for shopping". The agent fetched the bundle, then emitted a
// TemplateProposal with a completely INVENTED front — "BUILDING YOUR VISION" over a dark gradient — and
// described it as "both sides of the New Builds Construction design". The existing front was gone.
//
// CORRECTION (2026-08-05) — the original version of this comment gave two reasons and one was false:
//   * FALSE: "get_template_bundle returns no html by design (a design runs to 10k+ lines)".
//     getTemplateBundleById does return the artwork for both sides — data.front_template.html and
//     data.back_template.html — and the MCP was projecting it away by choice. Measured against a
//     44-row dump of the real templates table, a side is 8-16 KB and 35-56 LINES; the "10k+ lines"
//     figure was wrong by roughly 200x. (What IS true: 11 of those 44 rows exceed 1.4 MB because a
//     cropped image is inlined as base64 — handled by eliding the payload, see template-html.mjs.)
//   * TRUE: a TemplateProposal carrying front/back is a WHOLE design, so a back-only change could not
//     be expressed at all.
//
// Both halves are addressed now: get_template_side_html hands over the real html (with element ids),
// and a proposal may instead carry bundle_id + side + ops.
//
// The name check below therefore stays, with a different purpose. A proposal carrying front/back and
// named after a design that already exists is a REPLACEMENT dressed as an edit — the reported bug
// exactly — so it is refused and pointed at the edit path, rather than at the visual editor.
//
// No false positive on the normal revise loop: while a proposal is unsaved its name matches nothing in
// the library, so "request changes" → re-emit works exactly as before. Once it IS saved, a further
// change genuinely cannot be applied — so refusing then is right too.
//
// Scoped to LIBRARY proposals (no campaign_id). A campaign proposal is a campaign-specific copy and
// reusing the source design's name there is normal and harmless.
/**
 * Does `name` match a design already in the library? Pure, and exported, because ALL the judgement is
 * here: a bundle has no name of its own — the display name is a side template's description with a
 * trailing " Front"/" Back" token (the same rule bundleNameFromDescriptions and the frontend's
 * stripBundleSuffix apply), and comparison has to survive case and spacing differences.
 */
export function designNameClash(name, bundles) {
  const target = writeNorm(String(name ?? ""));
  if (!target) return null;
  for (const b of Array.isArray(bundles) ? bundles : []) {
    const desc = b?.front?.description ?? b?.back?.description
      ?? b?.front_template?.description ?? b?.back_template?.description ?? b?.name ?? "";
    const existing = writeNorm(String(desc).replace(/\s+(front|back)$/i, ""));
    if (existing && existing === target) return String(name).trim();
  }
  return null;
}

/**
 * A proposal is EITHER a new design (name + size + both sides) or an edit (bundle_id + side + ops).
 * Sending both is a model that has not decided which it is doing, and it must not be guessed at:
 * the ambiguity is exactly the reported bug — an "edit" that silently replaced the whole design.
 *
 * Checked on the RAW arguments, before validateUiFrame. The catalog schema is a union, and the
 * strip-parity walker resolves a union by required-key presence: a mixed payload matches the
 * new-design branch first, so `edit` would be quietly stripped and the proposal would go through as
 * a brand-new design. Refusing here is what stops that.
 */
export function mixedProposalModes(p) {
  if (!p || typeof p !== "object") return null;
  const isEdit = Array.isArray(p.ops) || typeof p.bundle_id === "string";
  const isNew = !!p.front || !!p.back;
  if (!isEdit || !isNew) return null;
  return {
    blocked: "proposal_is_new_or_edit_not_both",
    verified: false,
    retry: false,
    plain: "I got my wires crossed there — let me redo that.",
    note:
      "NOTHING was rendered. This proposal carries BOTH an edit (bundle_id/ops) and a whole design "
      + "(front/back). Those are different actions and I will not guess between them. To CHANGE a saved "
      + "design: send only bundle_id, side and ops — read the side first with get_template_side_html. To "
      + "propose a NEW design: send only name, postcard_size, front and back, and never name it after a "
      + "design that already exists.",
  };
}

async function savedDesignNameClash(proposalProps, userJwt) {
  if (!proposalProps || proposalProps.campaign_id) return null;
  const name = String(proposalProps.name ?? "").trim();
  if (!name) return null;
  const res = await callApi("getAllTemplatesBundlesV3", "GET", null, userJwt);
  if (!res || res.__error) return null; // cannot check → never block on a failed read
  return designNameClash(name, payload(res) ?? []);
}

