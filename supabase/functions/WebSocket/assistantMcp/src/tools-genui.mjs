// ── Validation parity with the frontend (bug-bash 2026-07-24) ─────────────────
// The frontend's zod catalog STRIPS unknown props (no .strict() anywhere) — but the generated
// JSON schema says additionalProperties:false, so ajv REJECTED frames the frontend would have
// rendered fine. Worse, for union-heavy components (TemplateProposal: 38 strict objects, 6
// anyOf) errors[0] was a bare "must NOT have additional properties" with the property name
// dropped, and the model looped retrying blind. Two fixes:
//   1. strip-parity: delete exactly the offending additional properties (ajv names them in
//      params.additionalProperty) and re-validate — mirroring what zod does on render;
//   2. when a frame still fails, report the DEEPEST real errors with property names and
//      allowed values, skipping anyOf/discriminator noise.
// Pick the union branch a value is aimed at: first by a `const` discriminator property
// (elements carry type:"shape"|"text"|…), else by required-key presence (fills: {color} vs
// {gradient}). Null when nothing matches — then we don't strip (validation reports normally).
function pickBranch(branches, value) {
  if (value == null || typeof value !== "object") return null;
  for (const b of branches) {
    const disc = Object.entries(b.properties ?? {}).find(([, s]) => s && s.const !== undefined);
    if (disc && value[disc[0]] === disc[1].const) return b;
  }
  for (const b of branches) {
    const req = b.required ?? [];
    if (req.length && req.every((k) => k in value)) return b;
  }
  return null;
}
// Schema-aware unknown-property strip (zod-parity: the frontend silently drops extras).
// IMPORTANT: naive stripping from ajv's additionalProperties errors is WRONG for unions — the
// non-matching branches flag every branch-specific prop as "additional" and blind deletion
// destroys valid elements. This walker descends the schema, resolves each union to ITS branch,
// and strips only genuinely-unknown keys. Mutates `value` in place.
function stripUnknown(schema, value) {
  if (!schema || value == null || typeof value !== "object") return;
  const branches = schema.oneOf ?? schema.anyOf;
  if (branches) {
    const b = pickBranch(branches, value);
    if (b) stripUnknown(b, value);
    return;
  }
  if (Array.isArray(value)) {
    if (schema.items) for (const item of value) stripUnknown(schema.items, item);
    return;
  }
  const props = schema.properties;
  if (props) {
    if (schema.additionalProperties === false) {
      for (const k of Object.keys(value)) if (!(k in props)) delete value[k];
    }
    for (const [k, sub] of Object.entries(props)) if (k in value) stripUnknown(sub, value[k]);
  }
}
function formatErrors(errors) {
  const real = (errors ?? []).filter((e) =>
    e.keyword !== "anyOf" && e.keyword !== "oneOf" &&
    !(e.keyword === "const" && /\/type$/.test(e.instancePath)) &&
    !(e.keyword === "enum" && /\/type$/.test(e.instancePath)));
  const pool = real.length ? real : (errors ?? []);
  // Union noise: several branches report "required" at the same path — fold them into one line.
  const requiredByPath = new Map();
  const rest = [];
  for (const e of pool) {
    if (e.keyword === "required" && e.params?.missingProperty) {
      const set = requiredByPath.get(e.instancePath) ?? new Set();
      set.add(e.params.missingProperty);
      requiredByPath.set(e.instancePath, set);
    } else {
      rest.push(e);
    }
  }
  const lines = [];
  for (const [path, propsSet] of requiredByPath) {
    const names = [...propsSet];
    lines.push(`${path || "(root)"} is missing ${names.length > 1 ? `one of: ${names.join(" | ")}` : `required property "${names[0]}"`}`);
  }
  for (const e of rest) {
    let msg = `${e.instancePath || "(root)"} ${e.message}`;
    if (e.params?.additionalProperty) msg += ` ("${e.params.additionalProperty}" is not a valid property here — remove it)`;
    if (e.params?.allowedValues) msg += ` (allowed: ${e.params.allowedValues.join(", ")})`;
    lines.push(msg);
  }
  return lines
    .sort((a, b) => b.indexOf(" ") - a.indexOf(" ")) // deepest paths first (longer pointer prefix)
    .slice(0, 3)
    .join("; ") || "invalid props";
}
// Validate one component's props with frontend strip-parity.
// Returns { ok:true, props } (possibly stripped) or { ok:false, error }.
function validateComponentProps(type, props) {
  const validate = validators[type];
  if (validate(props)) return { ok: true, props };
  const work = JSON.parse(JSON.stringify(props));
  stripUnknown(COMPONENT_SCHEMAS[type], work);
  if (validate(work)) return { ok: true, props: work };
  return { ok: false, error: formatErrors(validate.errors) };
}

// ── the model must not choose a singleton card's surface_id (2026-08-04) ──────
// REPORTED LIVE: the audience builder appeared twice in one conversation. The trace showed two
// create_campaign calls with IDENTICAL arguments producing two campaigns, and an emit_ui for each:
//   turn A   surface_id "audience-location-zone"          campaign_id 951d214a…
//   turn B   surface_id "audience_builder_location_zone"  campaign_id 97e650fa…
// The duplicate campaign is a separate defect. What belongs here is the second half: the model chose
// the surface_id both times, from memory of what it had used before, and PARAPHRASED itself. Since
// upsertSurface (frontend) and the consumed-surface lifecycle (D4, gateway) both key on surface_id, a
// paraphrase is a brand-new surface — so the same logical card renders twice instead of replacing
// itself in place. That is true even for a single campaign: any revise can duplicate a card this way.
//
// The fix is to remove the discretion. These components are SINGLETONS: exactly one audience builder
// exists per campaign, one uploader per referral gallery, one switch per organisation. Their identity
// is fully determined by (component type + the thing they act on), so the id is derived here and the
// model's is ignored. Two emits for the same target now collide by construction, which is what
// "re-emit to revise in place" was always supposed to mean.
//
// Deliberately NOT applied to the generic blocks (Text, DataTable, StatCards, CampaignList…). A
// campaign list and a chart are genuinely different surfaces even in the same conversation, and the
// model choosing ids there is correct — there is nothing intrinsic to derive from.
const SINGLETON_SURFACES = {
  AudienceBuilder: (p) => p?.campaign_id,
  LaunchButton: (p) => p?.campaign_id,
  VerifyAddressesButton: (p) => p?.campaign_id,
  AddressListUploader: (p) => p?.campaign_id,
  OrgSwitchButton: (p) => p?.organization_id,
  // A referral gallery is per referral; the org logo/gallery targets are one apiece.
  ImageUploader: (p) => (p?.referral_id ? `${p.target}:${p.referral_id}` : p?.target),
  // A proposal for a campaign replaces in place. A LIBRARY proposal has no target id, so it keeps the
  // model's id: the user may well be shown several candidate designs side by side.
  // An EDIT is per bundle-side — a revised edit of the same side must replace the earlier card, or the
  // user is left choosing between two versions of one change.
  TemplateProposal: (p) => (p?.bundle_id && p?.side ? `${p.bundle_id}:${p.side}` : p?.campaign_id),
};

/**
 * The surface_id a frame must use, or null to keep the model's.
 *
 * Applies when the frame contains EXACTLY ONE singleton component — the shape these cards always take.
 * A frame mixing two of them has no single identity, so it keeps the model's id rather than being
 * forced into one of them arbitrarily.
 */
export function derivedSurfaceId(components) {
  const hits = [];
  for (const n of components ?? []) {
    const keyOf = SINGLETON_SURFACES[n?.type];
    if (!keyOf) continue;
    const target = keyOf(n.props);
    if (typeof target === "string" && target.trim()) hits.push(`${n.type}:${target.trim()}`);
  }
  return hits.length === 1 ? hits[0] : null;
}

// ── opacity is a PERCENTAGE, and the model writes CSS fractions (2026-08-03) ───
// REPORTED LIVE, twice: asked to put a semi-transparent band behind text so it would read against the
// photos, the agent said it had ("every text element now sits on a 55%-opacity dark band") and the
// design looked unchanged. The trace showed it had done the job properly — a dark #1D1D20 rectangle
// before each text element, correct paint order, correct geometry — and written `opacity: 0.55`.
//
// The schema is `{minimum: 0, maximum: 100}`: a PERCENTAGE. So 0.55 validated, meaning 0.55%, and the
// generator emitted `opacity: 0.0055`. Three invisible bands. The model used the CSS 0-1 convention and
// nothing objected, because the wrong value sits comfortably inside the right range.
//
// This was never a false claim — the intent was exactly right and the units disagreed silently, which
// no amount of "verify what you assert" would have caught. It needs a check on the VALUE.
//
// NORMALISE rather than refuse. Every value in (0, 1] is meaningless as a percentage: 1% opacity is
// already invisible, so nobody has ever wanted 0.55%. Reading it as a fraction is unambiguous, and it
// is what the author meant. `opacity: 1` is treated as fully opaque for the same reason — 1% would make
// an element vanish, and 100 is the default anyway. Refusing instead would cost the user a turn to fix
// something we can already read correctly; the tool result names the correction so the model learns.
// THE SAME MISTAKE HAPPENS TO GRADIENT STOPS, and it reached production (trace 019fd190, 2026-08-05).
// Asked to bring the front's teal-to-orange gradient onto the back, the model wrote
//   stops: [{color:"#47BAD7", position:0}, {color:"#E36A00", position:1}]
// `position` is a PERCENTAGE too, so that is a gradient which finishes inside its first 1% — a flat
// orange panel, not the blend it described. Same silent failure as opacity: the wrong value sits
// comfortably inside the valid range.
//
// Reading them as fractions is unambiguous. A two-stop gradient at 0% and 1% is meaningless, and any
// stop list whose LARGEST position is <= 1 cannot be a percentage anyone intended — 0..1 is exactly
// how CSS colour stops are written elsewhere. Note the test is on the maximum across the whole list,
// not per stop, so a legitimate [0, 50, 100] is untouched even though its first stop is 0.
//
// AND IT HAS TO WALK EDIT OPS. The original version only looked at spec.front/back.elements, so once
// a proposal could carry `ops` instead, every element the agent ADDED to an existing design skipped
// the correction entirely. Found while reading the trace above, not by a test — which is why the
// tests below cover the ops path explicitly.
const OPACITY_HOSTS = ["front", "back"];

/** Fix one element's opacity in place; returns a description when it changed. */
function fixOpacity(el, where) {
  const o = el?.opacity;
  if (typeof o !== "number" || !Number.isFinite(o) || o <= 0 || o > 1) return null;
  // Rounded to 2dp: 0.55 * 100 is 55.00000000000001 in binary floating point, and that would ride
  // into the spec and out into the generated CSS. Two decimals is finer than any display can show.
  el.opacity = Math.round(o * 10000) / 100;
  return `${where} ${el.type ?? "element"} opacity: ${o} → ${el.opacity}`;
}

/** Fix a fill's gradient stop positions in place; returns a description when they changed. */
function fixFill(fill, where) {
  const stops = fill?.gradient?.stops;
  if (!Array.isArray(stops) || stops.length < 2) return null;
  const positions = stops.map((s) => s?.position).filter((p) => typeof p === "number" && Number.isFinite(p));
  if (positions.length !== stops.length) return null;      // a partly-positioned list is not ours to guess at
  const max = Math.max(...positions);
  if (max <= 0 || max > 1) return null;                    // 0-100 already, or nothing to scale
  const before = positions.join(",");
  stops.forEach((s) => { s.position = Math.round(s.position * 10000) / 100; });
  return `${where} gradient stops: ${before} → ${stops.map((s) => s.position).join(",")}`;
}

/** Walk anything element-shaped, wherever it lives. */
function fixElement(el, where, fixed) {
  const o = fixOpacity(el, where); if (o) fixed.push(o);
  const f = fixFill(el?.fill, where); if (f) fixed.push(f);
}

/**
 * Rewrite fractional opacities and gradient stop positions in place, for BOTH proposal shapes — a new
 * design's front/back elements and an edit's ops. Returns one label per correction, which the tool
 * result reports so the model does not describe the design using the number it sent.
 */
export function normalizeSpecOpacity(spec) {
  const fixed = [];
  if (!spec || typeof spec !== "object") return fixed;
  for (const side of OPACITY_HOSTS) {
    const s = spec[side];
    if (!s || typeof s !== "object") continue;
    const bg = fixFill(s.background, `${side} background`); if (bg) fixed.push(bg);
    if (!Array.isArray(s.elements)) continue;
    s.elements.forEach((el, i) => fixElement(el, `${side}[${i}]`, fixed));
  }
  if (Array.isArray(spec.ops)) {
    spec.ops.forEach((op, i) => {
      if (!op || typeof op !== "object") return;
      if (op.element) fixElement(op.element, `ops[${i}] add`, fixed);
      if (op.op === "set_background") {
        const f = fixFill(op.fill, `ops[${i}] set_background`); if (f) fixed.push(f);
      }
    });
  }
  return fixed;
}

// Normalize both accepted wire forms into { id, type, props }.
function normalizeEntry(entry) {
  if (!entry || typeof entry !== "object") return null;
  const id = entry.id;
  if (typeof id !== "string" || !id) return { error: "component entry missing string id" };
  if (entry.component && typeof entry.component === "object") {
    const keys = Object.keys(entry.component);
    if (keys.length !== 1) return { error: `component "${id}" must wrap exactly one type` };
    return { id, type: keys[0], props: entry.component[keys[0]] ?? {} };
  }
  if (typeof entry.componentType === "string") {
    return { id, type: entry.componentType, props: entry.properties ?? {} };
  }
  return { error: `component "${id}" has no component/componentType` };
}

